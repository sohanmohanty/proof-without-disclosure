"""Generate vectors/test-vectors.json — the file that pins the Python and
TypeScript implementations to each other.

Both test suites load this file and re-verify every entry. If either
implementation drifts from docs/format-spec.md, its tests fail. Regenerate
only when the format itself changes:  python scripts/generate_vectors.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from prooflab import commitments, hashing, merkle, schnorr  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[2]
OUT = REPO_ROOT / "vectors" / "test-vectors.json"


def sha256_vectors():
    texts = ["", "abc", "hello", "Hello", "proof without disclosure"]
    return [{"text": t, "sha256": hashing.hash_text(t)} for t in texts]


def commitment_vectors():
    cases = [
        ("hello", "00112233445566778899aabbccddeeff"),
        ("17", "e3a1c2d4f5a6b7c8d9e0f1a2b3c4d5e6"),
        ("the winner will be team blue", "0f1e2d3c4b5a69788796a5b4c3d2e1f0"),
    ]
    return [
        {
            "secret": secret,
            "salt": salt,
            "commitment": commitments.compute_commitment(secret, salt),
        }
        for secret, salt in cases
    ]


def merkle_vectors():
    out = []
    for items, prove_index in [
        (["alice@example.com", "bob@example.com",
          "carol@example.com", "dana@example.com"], 1),
        ([f"student_{i}" for i in range(5)], 4),   # odd count: promotion path
        (["single-item"], 0),
    ]:
        tree = merkle.build_tree(items)
        path = merkle.generate_proof(tree, prove_index)
        out.append({
            "items": items,
            "root": tree.root,
            "proof": {
                "index": prove_index,
                "item": items[prove_index],
                "leaf_hash": merkle.hash_leaf(items[prove_index]).hex(),
                "path": [{"position": s.position, "hash": s.hash}
                         for s in path],
            },
        })
    return out


def schnorr_vectors():
    out = []
    for group, x, r in [
        (schnorr.TOY_GROUP, 7, 5),
        (schnorr.REAL_GROUP, 0xDEADBEEFCAFEF00D, 0x123456789ABCDEF),
    ]:
        key = schnorr.keygen(group, x=x)
        proof = schnorr.prove(key, "hello prooflab", r=r)
        c = schnorr.fiat_shamir_challenge(group, proof.y, proof.R,
                                          proof.message)
        out.append({
            "group": group.name,
            "x": group.to_hex(x),
            "y": group.to_hex(proof.y),
            "r": group.to_hex(r),
            "R": group.to_hex(proof.R),
            "challenge": group.to_hex(c),
            "s": group.to_hex(proof.s),
            "message": proof.message,
        })
    return out


def signature_vector():
    """One signature generated by the Python side; the TypeScript suite
    verifies it with Web Crypto. ECDSA signing is randomized, but
    verification is deterministic, so a recorded signature is a valid pin."""
    try:
        from cryptography.hazmat.primitives.asymmetric import ec
        from prooflab import signatures
    except ImportError:
        return None
    private_key = ec.generate_private_key(ec.SECP256R1())
    message = "signed by prooflab (python) - verified everywhere"
    return {
        "algorithm": "ecdsa-p256-sha256",
        "message": message,
        "public_key": signatures.public_key_hex(private_key),
        "signature": signatures.sign(private_key, message.encode("utf-8")),
    }


def main() -> None:
    vectors = {
        "description": (
            "Shared test vectors for Proof Without Disclosure. The Python "
            "(prooflab) and TypeScript (website) implementations both verify "
            "every entry; see docs/format-spec.md for the byte-level rules."
        ),
        "sha256": sha256_vectors(),
        "commitments": commitment_vectors(),
        "merkle": merkle_vectors(),
        "schnorr": schnorr_vectors(),
        "signature": signature_vector(),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(vectors, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
