"""Schnorr identification protocol and Fiat-Shamir signatures.

The protocol proves knowledge of a discrete logarithm: the prover knows x
such that y = g^x (mod p), and convinces a verifier without revealing x.

    prover:   pick random nonce r,  send  R = g^r mod p      (commit)
    verifier: send random challenge c                        (challenge)
    prover:   send  s = r + c*x  (mod q)                     (respond)
    verifier: accept iff  g^s == R * y^c  (mod p)

Why it convinces (soundness): answering two different challenges c1, c2 for
the same R would yield s1 - s2 = (c1 - c2)*x mod q, which solves for x, so
a prover without x can only succeed by guessing the challenge: 1/q odds.

Why it reveals nothing (zero-knowledge): a transcript (R, c, s) can be forged
by anyone working backwards: pick c and s first, set R = g^s * y^(-c).
Real transcripts are indistinguishable from forged ones, so transcripts
cannot carry knowledge of x. (Interactive order matters: R must be fixed
*before* c is known. Forged transcripts pick c first, which is exactly why
they convince no one live but look identical afterwards.)

Fiat-Shamir: replace the verifier's random challenge with a hash,
c = H(group || y || R || message), making the proof non-interactive. The
prover can no longer pick c first, because c is determined by R. A Schnorr
*signature* is exactly this: a non-interactive zero-knowledge proof of
knowledge of the private key, bound to a message.

Groups: we work in the subgroup of quadratic residues of Z_p* for a safe
prime p = 2q + 1, generated by g = 4. For any safe prime p > 5, ord(4) is
exactly q: orders divide 2q, so ord(2) is q or 2q, and squaring makes
ord(4) = q either way. The real group uses the 2048-bit MODP prime from
RFC 3526; the toy group (p = 23) makes every number small enough to check
by hand, and small enough to break, which is the point of the demo.
"""

from __future__ import annotations

import hashlib
import secrets
from dataclasses import dataclass

DOMAIN = "prooflab-schnorr-v1"

