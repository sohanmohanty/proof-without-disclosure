@dataclass(frozen=True)
class Group:
    name: str
    p: int  # safe prime
    g: int  # generator of the order-q subgroup

    @property
    def q(self) -> int:
        return (self.p - 1) // 2

    @property
    def byte_len(self) -> int:
        return (self.p.bit_length() + 7) // 8

    def to_hex(self, value: int) -> str:
        """Zero-padded lowercase hex, fixed to the group's byte length."""
        return value.to_bytes(self.byte_len, "big").hex()


TOY_GROUP = Group("toy-23", p=23, g=4)
REAL_GROUP = Group("modp-2048", p=RFC3526_2048_P, g=4)
GROUPS = {g.name: g for g in (TOY_GROUP, REAL_GROUP)}


@dataclass(frozen=True)
class KeyPair:
    group: Group
    x: int  # private
    y: int  # public: g^x mod p


@dataclass(frozen=True)
class Proof:
    """Non-interactive (Fiat-Shamir) proof of knowledge of x for y = g^x."""
    group: Group
    y: int
    R: int
    s: int
    message: str


def keygen(group: Group, x: int | None = None) -> KeyPair:
    if x is None:
        x = 1 + secrets.randbelow(group.q - 1)
    if not 1 <= x < group.q:
        raise ValueError("private key must be in [1, q-1]")
    return KeyPair(group, x, pow(group.g, x, group.p))


def fiat_shamir_challenge(group: Group, y: int, R: int, message: str) -> int:
    """c = SHA-256(domain | group | y | R | message) mod q.

    Hashing y and R binds the challenge to this key and this commitment;
    hashing the message turns the proof into a signature on it.
    """
    preimage = "|".join(
        [DOMAIN, group.name, group.to_hex(y), group.to_hex(R), message]
    ).encode("utf-8")
    return int(hashlib.sha256(preimage).hexdigest(), 16) % group.q


def prove(key: KeyPair, message: str = "", r: int | None = None) -> Proof:
    """Produce a non-interactive proof. `r` is exposed only for test vectors:
    real callers must let the nonce be random (a reused or predictable nonce
    leaks the private key, the flaw that broke the PS3's ECDSA in 2010)."""
    group = key.group
    if r is None:
        r = 1 + secrets.randbelow(group.q - 1)
    R = pow(group.g, r, group.p)
    c = fiat_shamir_challenge(group, key.y, R, message)
    s = (r + c * key.x) % group.q
    return Proof(group, key.y, R, s, message)


def verify(proof: Proof) -> bool:
    group = proof.group
    if not (1 < proof.y < group.p and 1 <= proof.R < group.p):
        return False
    if not 0 <= proof.s < group.q:
        return False
    c = fiat_shamir_challenge(group, proof.y, proof.R, proof.message)
    left = pow(group.g, proof.s, group.p)
    right = (proof.R * pow(proof.y, c, group.p)) % group.p
    return left == right


# --- Interactive protocol pieces (used by the website's step-by-step demo
# --- and the CLI walkthrough; split out so each move is visible) ---------

def commit_nonce(group: Group, r: int | None = None) -> tuple[int, int]:
    """Prover step 1: returns (r, R)."""
    if r is None:
        r = 1 + secrets.randbelow(group.q - 1)
    return r, pow(group.g, r, group.p)


def random_challenge(group: Group) -> int:
    """Verifier step: uniform c in [0, q-1]."""
    return secrets.randbelow(group.q)


def respond(group: Group, x: int, r: int, c: int) -> int:
    """Prover step 2: s = r + c*x mod q."""
    return (r + c * x) % group.q


def check(group: Group, y: int, R: int, c: int, s: int) -> bool:
    """Verifier decision: g^s == R * y^c (mod p)."""
    return pow(group.g, s, group.p) == (R * pow(y, c, group.p)) % group.p


def forge_commitment(group: Group, y: int, guessed_c: int) -> tuple[int, int]:
    """Cheating prover: without x, guess the challenge c* in advance, pick s
    at random, and set R = g^s * y^(-c*). Verification passes iff the real
    challenge equals c*, with probability exactly 1/q. In the toy group q = 11,
    so a cheater slips through roughly one round in eleven; in the real
    group q is ~2^2046 and the strategy is hopeless."""
    s = secrets.randbelow(group.q)
    y_inv_c = pow(y, group.q - (guessed_c % group.q), group.p)
    R = (pow(group.g, s, group.p) * y_inv_c) % group.p
    return s, R


def brute_force_dlog(group: Group, y: int, limit: int = 1 << 22) -> int | None:
    """Recover x from y by trying every exponent. Instant for the toy group;
    the same loop on the 2048-bit group would outlast the universe. Exists
    to make 'discrete log is hard' something you can watch, not just read."""
    accumulator = 1
    for x in range(min(group.q, limit)):
        if accumulator == y:
            return x
        accumulator = (accumulator * group.g) % group.p
    return None
